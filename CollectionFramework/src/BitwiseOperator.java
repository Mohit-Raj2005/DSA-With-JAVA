public class BitwiseOperator {
    static void main(String[] args) {
        int a = 5;
        int b = 6;

        //bitwise AND & operator
        System.out.println(a & b );

        //bitwise OR | operator
        System.out.println(a | b );

        //bitwise XOR ^ operator
        System.out.println(a ^ b );
    }
}
